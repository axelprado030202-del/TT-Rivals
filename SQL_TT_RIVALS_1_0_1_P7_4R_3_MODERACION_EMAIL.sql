create or replace function public.tt_v76_user_is_hidden(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path=''
as $function$
  select exists(
    select 1
    from auth.users u
    where u.id=p_user_id
      and (
        exists(
          select 1
          from public.account_access_bans_v75 b
          where b.active
            and (
              b.user_id=u.id
              or b.email_key=public.tt_v75_email_key(u.email)
            )
            and (
              b.ban_type='email_permanent'
              or (b.ban_type='temporary' and b.blocked_until>now())
            )
        )
        or exists(
          select 1
          from public.device_access_bans_v75 d
          where d.active
            and (
              d.source_user_id=u.id
              or exists(
                select 1
                from public.installation_accounts_v58 ia
                where ia.user_id=u.id
                  and ia.installation_id=d.installation_id
              )
            )
        )
        or exists(
          select 1
          from public.ip_access_bans_v75 ib
          where ib.active
            and (
              ib.source_user_id=u.id
              or exists(
                select 1
                from public.access_observations_v75 o
                where o.user_id=u.id
                  and o.ip_hash=ib.ip_hash
              )
            )
        )
      )
  );
$function$;

revoke all on function public.tt_v76_user_is_hidden(uuid) from public,anon,authenticated;

-- Conserva el hook ya activado en Supabase y añade unicidad canónica de correo.
-- Para Gmail también bloquea variantes con puntos o sufijos +alias.
create or replace function public.hook_before_user_created_v75(event jsonb)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_user_id uuid:=(event->'user'->>'id')::uuid;
  v_email text:=event->'user'->>'email';
  v_email_key text:=public.tt_v75_email_key(event->'user'->>'email');
  v_installation uuid;
  v_ip text:=event->'metadata'->>'ip_address';
  v_decision jsonb;
begin
  begin
    v_installation:=nullif(event->'user'->'user_metadata'->>'installation_id','')::uuid;
  exception when others then
    v_installation:=null;
  end;

  v_decision:=public.tt_v75_access_decision(v_email,v_installation,v_user_id,v_ip,false,'signup');
  if not coalesce((v_decision->>'allowed')::boolean,false) then
    return jsonb_build_object('error',jsonb_build_object(
      'http_code',403,
      'message',v_decision->>'message'
    ));
  end if;

  delete from auth.users u
  where u.id<>v_user_id
    and u.email_confirmed_at is null
    and u.created_at<now()-interval '7 days'
    and public.tt_v75_email_key(u.email)=v_email_key;

  if exists(
    select 1
    from auth.users u
    where u.id<>v_user_id
      and public.tt_v75_email_key(u.email)=v_email_key
  ) then
    return jsonb_build_object('error',jsonb_build_object(
      'http_code',400,
      'message','Ese correo ya está registrado o no puede utilizarse'
    ));
  end if;

  perform public.tt_v75_access_decision(v_email,v_installation,v_user_id,v_ip,true,'signup');
  return '{}'::jsonb;
end;
$function$;

revoke all on function public.hook_before_user_created_v75(jsonb) from public,anon,authenticated;
grant execute on function public.hook_before_user_created_v75(jsonb) to supabase_auth_admin;

