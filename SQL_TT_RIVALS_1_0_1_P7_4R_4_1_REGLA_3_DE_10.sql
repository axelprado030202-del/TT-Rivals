create or replace function public.get_my_integrity_status_v78()
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_user uuid:=auth.uid();
  v_sanction jsonb;
  v_holds jsonb;
  v_notifications jsonb;
begin
  if v_user is null then raise exception 'Sesión requerida'; end if;
  perform public.tt_v78_expire_sanctions();
  select to_jsonb(s) into v_sanction
  from public.integrity_sanctions_v78 s
  where s.user_id=v_user and s.status='active' and s.ends_at>now()
  order by s.created_at desc limit 1;
  select coalesce(jsonb_agg(to_jsonb(h) order by h.created_at desc),'[]'::jsonb) into v_holds
  from public.integrity_match_holds_v78 h
  where h.status='pending' and v_user=any(h.participants);
  select coalesce(jsonb_agg(to_jsonb(n) order by n.created_at desc),'[]'::jsonb) into v_notifications
  from public.integrity_notifications_v78 n
  where n.user_id=v_user and n.read_at is null;
  update public.integrity_notifications_v78 set read_at=now()
  where user_id=v_user and read_at is null;
  return jsonb_build_object(
    'active',v_sanction is not null,'sanction',v_sanction,
    'pending_holds',v_holds,'notifications',v_notifications
  );
end;
$function$;

create or replace function public.submit_integrity_appeal_v78(p_message text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare v_user uuid:=auth.uid();v_id bigint;
begin
  if v_user is null then raise exception 'Sesión requerida'; end if;
