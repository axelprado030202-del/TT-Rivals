set active=false
where active and signal_type<>'duration_extreme';

update public.auto_moderation_cases_v77
set status='cleared',score=0,distinct_matches=0,distinct_signal_types=0,
    evidence='[]'::jsonb,updated_at=now()
where status in('observed','would_suspend');

