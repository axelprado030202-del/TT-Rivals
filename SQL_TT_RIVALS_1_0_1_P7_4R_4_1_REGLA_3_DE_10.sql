create or replace function public.admin_resolve_integrity_hold_v78(
  p_match_id bigint,p_action text,p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_admin uuid:=auth.uid();
  v_hold public.integrity_match_holds_v78%rowtype;
  v_match public.matches%rowtype;
  v_doc jsonb;
  v_submitter uuid;
  v_confirmer uuid;
  v_old_sub text:=current_setting('request.jwt.claim.sub',true);
  v_old_claims text:=current_setting('request.jwt.claims',true);
begin
  if not public.tt_v58_is_admin(v_admin) then raise exception 'Solo Administrador'; end if;
  if p_action not in('approve','annul') then raise exception 'Acción inválida'; end if;
  select * into v_hold from public.integrity_match_holds_v78
  where match_id=p_match_id and status='pending' for update;
  if not found then raise exception 'La retención no existe o ya fue resuelta'; end if;
  select * into v_match from public.matches where id=p_match_id for update;
  if not found then raise exception 'Partido no encontrado'; end if;

  if p_action='approve' then
    update public.integrity_match_holds_v78
    set status='approved',resolved_at=now(),resolved_by=v_admin,resolution_note=nullif(trim(coalesce(p_note,'')),'')
    where match_id=p_match_id;
    update public.auto_moderation_signals_v77 set active=false where match_id=p_match_id;
    update public.integrity_sanctions_v78
    set status='revoked',reviewed_by=v_admin,reviewed_at=now(),review_note='Partido validado por Admin',updated_at=now()
    where trigger_match_id=p_match_id and status='active';
    v_doc:=to_jsonb(v_match);
    v_submitter:=nullif(v_doc->>'result_submitted_by','')::uuid;
    v_confirmer:=case when v_submitter=v_match.player1_id then v_match.player2_id else v_match.player1_id end;
    perform set_config('request.jwt.claim.sub',v_confirmer::text,true);
    perform set_config('request.jwt.claims',jsonb_build_object('sub',v_confirmer,'role','authenticated')::text,true);
    perform public.confirm_match_result(p_match_id);
    perform set_config('request.jwt.claim.sub',coalesce(v_old_sub,''),true);
    perform set_config('request.jwt.claims',coalesce(v_old_claims,'{}'),true);
    update public.auto_moderation_cases_v77
    set status='dismissed',reviewed_by=v_admin,review_note='Partido validado por Admin',updated_at=now()
    where user_id=any(v_hold.triggered_users) and status in('observed','would_suspend','suspended');
    insert into public.integrity_notifications_v78(user_id,title,message)
    select participant,'Decisión de integridad: partido validado',
      'El partido #'||p_match_id||' fue validado por el administrador y sus consecuencias oficiales fueron aplicadas.'
    from unnest(v_hold.participants) as u(participant);
  else
    update public.matches set result_status='annulled',confirmed_at=null where id=p_match_id;
    update public.integrity_match_holds_v78
    set status='annulled',resolved_at=now(),resolved_by=v_admin,resolution_note=nullif(trim(coalesce(p_note,'')),'')
    where match_id=p_match_id;
    insert into public.integrity_notifications_v78(user_id,title,message)
    select participant,'Decisión de integridad: partido anulado',
      'El partido #'||p_match_id||' fue anulado y no aportará Elo ni estadísticas oficiales.'
    from unnest(v_hold.participants) as u(participant);
  end if;
  return public.admin_get_auto_moderation_v77(50);
end;
$function$;

create or replace function public.admin_get_auto_moderation_v77(p_limit integer default 50)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare v_admin uuid:=auth.uid();v_config jsonb;v_cases jsonb;v_summary jsonb;v_holds jsonb;
begin
  if not public.tt_v58_is_admin(v_admin) then raise exception 'Solo Administrador'; end if;
  perform public.tt_v78_expire_sanctions();
  select to_jsonb(c) into v_config from tt_private_v77.auto_moderation_config_v77 c where singleton=true;
  select jsonb_build_object(
    'open_cases',count(*) filter(where status in('observed','would_suspend','suspended')),
    'threshold_cases',count(*) filter(where status in('would_suspend','suspended')),
    'automatic_suspensions',(select count(*) from public.integrity_sanctions_v78 where status='active' and ends_at>now()),
    'pending_holds',(select count(*) from public.integrity_match_holds_v78 where status='pending')
  ) into v_summary from public.auto_moderation_cases_v77;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.updated_at desc),'[]'::jsonb) into v_cases
  from(
    select c.id,c.user_id,c.status,c.score,c.distinct_matches,c.distinct_signal_types,
      c.evaluation_mode,c.suspension_until,c.evidence,c.created_at,c.updated_at,c.review_note,
      p.username,p.first_name,p.last_name,p.profile_photo_url,
      to_jsonb(s) as sanction
    from public.auto_moderation_cases_v77 c
    left join public.profiles p on p.id=c.user_id
    left join lateral(
      select sx.* from public.integrity_sanctions_v78 sx
      where sx.user_id=c.user_id order by sx.created_at desc limit 1
    ) s on true
    where c.status in('observed','would_suspend','suspended')
    order by c.updated_at desc limit greatest(1,least(200,coalesce(p_limit,50)))
  ) x;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) into v_holds
  from(
    select h.*,p1.username as player1_username,p2.username as player2_username
    from public.integrity_match_holds_v78 h
    left join public.matches m on m.id=h.match_id
    left join public.profiles p1 on p1.id=m.player1_id
    left join public.profiles p2 on p2.id=m.player2_id
    where h.status='pending'
    order by h.created_at desc limit 100
  ) x;
  return jsonb_build_object('config',v_config,'summary',v_summary,'cases',v_cases,'holds',v_holds);
end;
$function$;

create or replace function public.admin_reprocess_auto_moderation_v77(
  p_days integer default 7,p_limit integer default 500
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare v_admin uuid:=auth.uid();v_days integer:=greatest(1,least(14,coalesce(p_days,7)));v_limit integer:=greatest(1,least(1000,coalesce(p_limit,500)));v_row record;v_count integer:=0;
begin
  if not public.tt_v58_is_admin(v_admin) then raise exception 'Solo Administrador'; end if;
  if (select mode from tt_private_v77.auto_moderation_config_v77 where singleton=true)='paused' then
    raise exception 'El motor está pausado. Elegí Simulación antes de reanalizar';
  end if;
  update public.auto_moderation_signals_v77 set active=false
  where created_at>=now()-make_interval(days=>v_days);
  update public.auto_moderation_cases_v77 set status='cleared',updated_at=now()
  where status in('observed','would_suspend');
  for v_row in
    select m.id,public.tt_v78_match_occurred_at(to_jsonb(m)) occurred_at
    from public.matches m
    where lower(coalesce(to_jsonb(m)->>'result_status',''))='confirmed'
      and lower(coalesce(to_jsonb(m)->>'match_type','ranked')) in('ranked','competitive','casual')
      and public.tt_v78_match_occurred_at(to_jsonb(m))>=now()-make_interval(days=>v_days)
    order by occurred_at asc limit v_limit
  loop
    perform public.tt_v77_evaluate_match(v_row.id,false);v_count:=v_count+1;
  end loop;
  return public.admin_get_auto_moderation_v77(50)||jsonb_build_object('reprocessed_matches',v_count);
end;
$function$;

