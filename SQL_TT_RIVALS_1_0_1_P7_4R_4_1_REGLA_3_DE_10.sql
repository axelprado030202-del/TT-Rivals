create or replace function public.tt_v78_create_sanction(
  p_user_id uuid,
  p_match_id bigint,
  p_competitive_locked boolean,
  p_evidence jsonb
)
returns public.integrity_sanctions_v78
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_row public.integrity_sanctions_v78%rowtype;
  v_previous integer:=0;
  v_level smallint:=1;
  v_hours integer:=24;
  v_message text;
begin
  perform public.tt_v78_expire_sanctions();
  select * into v_row from public.integrity_sanctions_v78
  where user_id=p_user_id and status='active' and ends_at>now()
  order by created_at desc limit 1 for update;
  if found then return v_row; end if;

  select count(*)::integer into v_previous
  from public.integrity_sanctions_v78
  where user_id=p_user_id and status<>'revoked'
    and created_at>=now()-interval '90 days';
  v_level:=least(3,v_previous+1)::smallint;
  v_hours:=case v_level when 1 then 24 when 2 then 72 else 168 end;
  v_message:='Detectamos 3 partidos de menos de un minuto entre tus últimos 10 del día. '
    ||case when p_competitive_locked
      then 'Las partidas con Elo y los casuales oficiales quedan bloqueados temporalmente. '
      else 'Los casuales oficiales quedan bloqueados temporalmente. ' end
    ||'La sanción termina el '||to_char(now()+make_interval(hours=>v_hours),'DD/MM/YYYY HH24:MI')
    ||'. Las reincidencias son acumulables y progresivamente más extensas.';

  insert into public.integrity_sanctions_v78(
    user_id,trigger_match_id,level,casual_locked,competitive_locked,
    ends_at,reason,evidence
  ) values(
    p_user_id,p_match_id,v_level,true,p_competitive_locked,
    now()+make_interval(hours=>v_hours),
    '3 partidos de menos de 60 segundos entre los últimos 10 del día',
    coalesce(p_evidence,'{}'::jsonb)
  ) returning * into v_row;

  insert into public.integrity_notifications_v78(user_id,sanction_id,title,message)
  values(p_user_id,v_row.id,'Advertencia de integridad',v_message);
  return v_row;
end;
$function$;

-- Obtiene la mayor cantidad de partidos cortos que apareció en cualquier
-- ventana móvil de 10 partidos del usuario durante los últimos 7 días.
create or replace function public.tt_v78_best_short_window(p_user_id uuid)
returns jsonb
language sql
stable
security definer
set search_path=''
as $function$
  with config as(
    select lookback_days,short_match_seconds,recent_matches_limit,evaluation_timezone
    from tt_private_v77.auto_moderation_config_v77 where singleton=true
  ), base as(
    select
      m.id as match_id,
      lower(coalesce(to_jsonb(m)->>'match_type','ranked')) as match_type,
      public.tt_v78_match_duration_seconds(to_jsonb(m)) as duration_seconds,
      public.tt_v78_match_occurred_at(to_jsonb(m)) as occurred_at,
      timezone((select evaluation_timezone from config),public.tt_v78_match_occurred_at(to_jsonb(m)))::date as local_day
    from public.matches m,config c
    where lower(coalesce(to_jsonb(m)->>'result_status',''))='confirmed'
      and (m.player1_id=p_user_id or m.player2_id=p_user_id)
      and lower(coalesce(to_jsonb(m)->>'match_type','ranked')) in('ranked','competitive','casual')
      and public.tt_v78_match_occurred_at(to_jsonb(m))>=now()-make_interval(days=>c.lookback_days)
  ), rolling as(
    select b.*,
      count(*) filter(where b.duration_seconds<(select short_match_seconds from config))
        over(partition by b.local_day order by b.occurred_at,b.match_id
             rows between 9 preceding and current row) as short_count
    from base b
  ), best as(
    select * from rolling order by short_count desc,occurred_at desc limit 1
  ), window_rows as(
    select b.* from base b,best x
    where b.local_day=x.local_day and (b.occurred_at,b.match_id)<=(x.occurred_at,x.match_id)
    order by b.occurred_at desc,b.match_id desc
    limit (select recent_matches_limit from config)
  ), short_rows as(
    select * from window_rows
    where duration_seconds<(select short_match_seconds from config)
  )
  select jsonb_build_object(
    'short_count',coalesce((select short_count from best),0),
    'local_day',(select local_day from best),
    'competitive_involved',coalesce((select bool_or(match_type<>'casual') from short_rows),false),
    'match_types',coalesce((select jsonb_agg(distinct match_type) from short_rows),'[]'::jsonb),
    'matches',coalesce((select jsonb_agg(jsonb_build_object(
      'match_id',match_id,'match_type',match_type,'duration_seconds',duration_seconds,'occurred_at',occurred_at
    ) order by occurred_at desc) from short_rows),'[]'::jsonb)
  );
$function$;

create or replace function public.tt_v77_evaluate_user(
  p_user_id uuid,
  p_allow_enforcement boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_config tt_private_v77.auto_moderation_config_v77%rowtype;
  v_case public.auto_moderation_cases_v77%rowtype;
  v_window jsonb;
  v_short integer:=0;
  v_types integer:=0;
  v_status text:='observed';
begin
  if public.tt_v77_is_protected_user(p_user_id) then
    return jsonb_build_object('user_id',p_user_id,'protected',true,'status','ignored');
  end if;
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text,78));
  select * into v_config from tt_private_v77.auto_moderation_config_v77 where singleton=true;
  v_window:=public.tt_v78_best_short_window(p_user_id);
  v_short:=coalesce((v_window->>'short_count')::integer,0);
  select count(*)::integer into v_types from jsonb_array_elements(coalesce(v_window->'match_types','[]'::jsonb));

  select * into v_case from public.auto_moderation_cases_v77
  where user_id=p_user_id and status in('observed','would_suspend','suspended')
  order by updated_at desc limit 1 for update;

  if exists(select 1 from public.integrity_sanctions_v78 s where s.user_id=p_user_id and s.status='active' and s.ends_at>now()) then
    v_status:='suspended';
  elsif v_short>=v_config.short_matches_required then
    v_status:='would_suspend';
  elsif v_short=0 then
    v_status:='cleared';
  end if;

  if v_status='cleared' then
    if v_case.id is not null then
      update public.auto_moderation_cases_v77
      set status='cleared',score=0,distinct_matches=0,distinct_signal_types=0,
          evidence='[]'::jsonb,evaluation_mode=v_config.mode,updated_at=now()
      where id=v_case.id;
    end if;
    return jsonb_build_object('user_id',p_user_id,'status','cleared','short_matches',0);
  end if;

  if v_case.id is null then
    insert into public.auto_moderation_cases_v77(
      user_id,status,score,distinct_matches,distinct_signal_types,evaluation_mode,evidence
    ) values(p_user_id,v_status,v_short,v_short,v_types,v_config.mode,v_window)
    returning * into v_case;
  else
    update public.auto_moderation_cases_v77
    set status=v_status,score=v_short,distinct_matches=v_short,
        distinct_signal_types=v_types,evaluation_mode=v_config.mode,
        suspension_until=(select max(s.ends_at) from public.integrity_sanctions_v78 s
          where s.user_id=p_user_id and s.status='active'),
        evidence=v_window,updated_at=now()
    where id=v_case.id returning * into v_case;
  end if;

  return jsonb_build_object(
    'case_id',v_case.id,'user_id',p_user_id,'status',v_status,
    'short_matches',v_short,'window',v_window
  );
end;
$function$;

create or replace function public.tt_v77_evaluate_match(
  p_match_id bigint,
  p_allow_enforcement boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_match public.matches%rowtype;
  v_doc jsonb;
  v_type text;
  v_occurred timestamptz;
  v_gameplay integer;
  v_limit integer:=60;
  v_mode text:='observe';
  v_player uuid;
  v_opponent uuid;
  v_results jsonb:='[]'::jsonb;
begin
  select * into v_match from public.matches m where m.id=p_match_id;
  if not found then return jsonb_build_object('ignored',true,'reason','match_not_found'); end if;
  v_doc:=to_jsonb(v_match);
  if lower(coalesce(v_doc->>'result_status',''))<>'confirmed' then
    return jsonb_build_object('ignored',true,'reason','not_confirmed');
  end if;
  if exists(select 1 from public.integrity_match_holds_v78 h where h.match_id=p_match_id and h.status='approved') then
    return jsonb_build_object('ignored',true,'reason','admin_approved');
  end if;
  v_type:=lower(coalesce(v_doc->>'match_type','ranked'));
  if v_type not in('ranked','competitive','casual') then
    return jsonb_build_object('ignored',true,'reason','unsupported_type');
  end if;
  select mode,short_match_seconds into v_mode,v_limit
  from tt_private_v77.auto_moderation_config_v77 where singleton=true;
  if v_mode='paused' then return jsonb_build_object('ignored',true,'reason','paused'); end if;

  v_occurred:=coalesce(public.tt_v78_match_occurred_at(v_doc),now());
  v_gameplay:=public.tt_v78_match_duration_seconds(v_doc);
  foreach v_player in array array[v_match.player1_id,v_match.player2_id]
  loop
    if v_player is null or public.tt_v77_is_protected_user(v_player) then continue; end if;
    v_opponent:=case when v_player=v_match.player1_id then v_match.player2_id else v_match.player1_id end;
    if v_gameplay is not null and v_gameplay<v_limit then
      perform public.tt_v77_record_signal(
        v_player,v_opponent,p_match_id,'duration_extreme',1,
        jsonb_build_object('gameplay_seconds',v_gameplay,'match_type',v_type,'rule','3_short_in_last_10_day'),
        v_occurred
      );
    end if;
    v_results:=v_results||jsonb_build_array(public.tt_v77_evaluate_user(v_player,false));
  end loop;
  return jsonb_build_object('match_id',p_match_id,'duration_seconds',v_gameplay,'evaluations',v_results);
exception when others then
  raise warning 'TT V78 no pudo evaluar partido %: %',p_match_id,sqlerrm;
  return jsonb_build_object('match_id',p_match_id,'error',sqlerrm);
end;
$function$;

-- Puerta atómica: en modo activo, el tercer partido corto queda retenido antes
-- de que confirm_match_result aplique Elo o estadísticas.
create or replace function public.confirm_match_result_integrity_v78(p_match_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_match public.matches%rowtype;
  v_doc jsonb;
  v_user uuid:=auth.uid();
  v_type text;
  v_mode text;
  v_limit integer;
  v_duration integer;
  v_occurred timestamptz;
  v_day date;
  v_player uuid;
  v_opponent uuid;
  v_previous_short integer:=0;
  v_competitive_involved boolean:=false;
  v_player_competitive boolean:=false;
  v_triggered uuid[]:='{}'::uuid[];
  v_participants uuid[];
  v_sanction public.integrity_sanctions_v78%rowtype;
  v_existing public.integrity_sanctions_v78%rowtype;
begin
  if v_user is null then raise exception 'Sesión requerida'; end if;
  select * into v_match from public.matches where id=p_match_id for update;
  if not found then raise exception 'Partido no encontrado'; end if;
  if v_user not in(v_match.player1_id,v_match.player2_id) then raise exception 'No participás en este partido'; end if;
  v_doc:=to_jsonb(v_match);
  v_type:=lower(coalesce(v_doc->>'match_type','ranked'));
  v_participants:=array[v_match.player1_id,v_match.player2_id];

  select * into v_existing from public.tt_v78_active_sanction(v_user);
  if v_existing.id is not null and (
    (v_type='casual' and v_existing.casual_locked)
    or (v_type<>'casual' and v_existing.competitive_locked)
  ) then
    return jsonb_build_object(
      'integrity_locked',true,'sanction_id',v_existing.id,'ends_at',v_existing.ends_at,
      'message','Esta modalidad está bloqueada temporalmente por una sanción de integridad.'
    );
  end if;

  select mode,short_match_seconds into v_mode,v_limit
  from tt_private_v77.auto_moderation_config_v77 where singleton=true;
  v_duration:=public.tt_v78_match_duration_seconds(v_doc);
  v_occurred:=coalesce(public.tt_v78_match_occurred_at(v_doc),now());
  v_day:=timezone('America/Montevideo',v_occurred)::date;

  if v_mode='enforce' and v_duration is not null and v_duration<v_limit then
    foreach v_player in array v_participants loop
      if public.tt_v77_is_protected_user(v_player) then continue; end if;
      v_opponent:=case when v_player=v_match.player1_id then v_match.player2_id else v_match.player1_id end;
      select
        count(*) filter(where src.duration_seconds<v_limit)::integer,
        coalesce(bool_or(src.duration_seconds<v_limit and src.match_type<>'casual'),false)
      into v_previous_short,v_player_competitive
      from(
        select
          lower(coalesce(to_jsonb(m)->>'match_type','ranked')) as match_type,
          public.tt_v78_match_duration_seconds(to_jsonb(m)) as duration_seconds
        from public.matches m
        where lower(coalesce(to_jsonb(m)->>'result_status',''))='confirmed'
          and (m.player1_id=v_player or m.player2_id=v_player)
          and timezone('America/Montevideo',public.tt_v78_match_occurred_at(to_jsonb(m)))::date=v_day
        order by public.tt_v78_match_occurred_at(to_jsonb(m)) desc,m.id desc
        limit 9
      ) src;

      perform public.tt_v77_record_signal(
        v_player,v_opponent,p_match_id,'duration_extreme',1,
        jsonb_build_object('gameplay_seconds',v_duration,'match_type',v_type,'candidate_hold',true),v_occurred
      );
      if v_previous_short>=2 then v_triggered:=array_append(v_triggered,v_player); end if;
      v_competitive_involved:=v_competitive_involved or v_player_competitive or v_type<>'casual';
    end loop;
  end if;

  if cardinality(v_triggered)>0 then
    insert into public.integrity_match_holds_v78(
      match_id,participants,triggered_users,match_type,hold_scope,duration_seconds,evidence
    ) values(
      p_match_id,v_participants,v_triggered,v_type,
      case when v_type='casual' then 'statistics' else 'elo_and_statistics' end,
      v_duration,jsonb_build_object('rule','3_short_in_last_10_day','threshold_seconds',v_limit)
    ) on conflict(match_id) do nothing;

    foreach v_player in array v_triggered loop
      select * into v_sanction from public.tt_v78_create_sanction(
        v_player,p_match_id,v_competitive_involved,
        jsonb_build_object('duration_seconds',v_duration,'match_type',v_type,'short_matches',3,'window_size',10)
      );
      update public.auto_moderation_cases_v77
      set status='suspended',score=3,distinct_matches=3,distinct_signal_types=1,
          evaluation_mode='enforce',suspension_until=v_sanction.ends_at,
          evidence=v_sanction.evidence,updated_at=now()
      where user_id=v_player and status in('observed','would_suspend','suspended');
      if not found then
        insert into public.auto_moderation_cases_v77(
          user_id,status,score,distinct_matches,distinct_signal_types,
          evaluation_mode,suspension_until,evidence
        ) values(v_player,'suspended',3,3,1,'enforce',v_sanction.ends_at,v_sanction.evidence);
      end if;
    end loop;
    return jsonb_build_object(
      'integrity_hold',true,'match_id',p_match_id,'duration_seconds',v_duration,
      'triggered_users',v_triggered,'message','El resultado quedó en revisión de integridad y todavía no modificó Elo ni estadísticas.'
    );
  end if;

  perform public.confirm_match_result(p_match_id);
  return jsonb_build_object('confirmed',true,'match_id',p_match_id);
end;
$function$;

-- Impide iniciar o aceptar desafíos oficiales durante la restricción.
create or replace function public.tt_v78_challenge_guard()
returns trigger
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_user uuid:=auth.uid();
  v_doc jsonb:=to_jsonb(new);
  v_type text:=lower(coalesce(v_doc->>'match_type','ranked'));
  v_sanction public.integrity_sanctions_v78%rowtype;
begin
  if v_user is null or public.tt_v77_is_protected_user(v_user) then return new; end if;
  select * into v_sanction from public.tt_v78_active_sanction(v_user);
  if v_sanction.id is null then return new; end if;
  if (v_type='casual' and v_sanction.casual_locked)
     or (v_type<>'casual' and v_sanction.competitive_locked) then
    raise exception 'Modalidad bloqueada hasta %. Podés apelar desde el aviso de integridad.',
      to_char(v_sanction.ends_at at time zone 'America/Montevideo','DD/MM/YYYY HH24:MI');
  end if;
  return new;
end;
$function$;

