-- TT Rivals 1.0.1 — P7.4R.4.1 Integridad 3 de 10
-- Regla: dentro de un mismo día (Uruguay), 3 partidos de menos de 60 s
-- entre los últimos 10 activan una retención preventiva.
-- Se instala en SIMULACIÓN. No aplica sanciones reales hasta que el Admin active el motor.

begin;

do $preflight$
begin
  if to_regclass('public.auto_moderation_signals_v77') is null
     or to_regclass('public.auto_moderation_cases_v77') is null
     or to_regclass('tt_private_v77.auto_moderation_config_v77') is null then
    raise exception 'Falta P7.4R.4: instalá primero la moderación automática base';
  end if;
  if to_regprocedure('public.confirm_match_result(bigint)') is null then
    raise exception 'No se encontró public.confirm_match_result(bigint). No se modificó la confirmación';
  end if;
end;
$preflight$;

