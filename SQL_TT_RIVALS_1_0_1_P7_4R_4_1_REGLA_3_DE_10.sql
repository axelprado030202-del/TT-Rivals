create or replace function public.tt_v78_match_occurred_at(p_doc jsonb)
returns timestamptz
language plpgsql
stable
set search_path=''
as $function$
begin
  return coalesce(
    nullif(p_doc->>'result_submitted_at','')::timestamptz,
    nullif(p_doc->>'confirmed_at','')::timestamptz,
    nullif(p_doc->>'created_at','')::timestamptz
  );
exception when others then
  return null;
end;
$function$;

create or replace function public.tt_v78_match_duration_seconds(p_doc jsonb)
returns integer
language plpgsql
stable
set search_path=''
as $function$
declare
  v_seconds numeric;
  v_started timestamptz;
  v_finished timestamptz;
begin
  v_seconds:=public.tt_v77_json_number(p_doc,'gameplay_seconds');
  if v_seconds is not null then return greatest(0,v_seconds::integer); end if;

  v_started:=coalesce(
    nullif(p_doc->>'accepted_at','')::timestamptz,
    nullif(p_doc->>'started_at','')::timestamptz,
    nullif(p_doc->>'created_at','')::timestamptz
  );
  v_finished:=coalesce(
    nullif(p_doc->>'result_submitted_at','')::timestamptz,
    nullif(p_doc->>'confirmed_at','')::timestamptz
  );
  if v_started is null or v_finished is null then return null; end if;
  return greatest(0,extract(epoch from (v_finished-v_started))::integer);
exception when others then
  return null;
end;
$function$;

