  add column if not exists short_match_seconds integer not null default 60,
  add column if not exists short_matches_required integer not null default 3,
  add column if not exists recent_matches_limit integer not null default 10,
  add column if not exists evaluation_timezone text not null default 'America/Montevideo';

-- Toda instalación o actualización vuelve deliberadamente a simulación.
update tt_private_v77.auto_moderation_config_v77
set mode='observe',
    lookback_days=7,
    short_match_seconds=60,
    short_matches_required=3,
    recent_matches_limit=10,
    evaluation_timezone='America/Montevideo',
    updated_at=now()
where singleton=true;

