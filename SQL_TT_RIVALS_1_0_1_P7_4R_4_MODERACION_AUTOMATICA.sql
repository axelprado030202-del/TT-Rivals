$function$;

create or replace function public.admin_reprocess_auto_moderation_v77(
  p_days integer default 7,
  p_limit integer default 500
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_admin uuid:=auth.uid();
  v_days integer:=greatest(1,least(14,coalesce(p_days,7)));
  v_limit integer:=greatest(1,least(1000,coalesce(p_limit,500)));
  v_row record;
  v_count integer:=0;
  v_mode text;
begin
  if not public.tt_v58_is_admin(v_admin) then raise exception 'Solo Administrador'; end if;
  select c.mode into v_mode
  from tt_private_v77.auto_moderation_config_v77 c
  where c.singleton=true;
  if v_mode='paused' then raise exception 'El motor está pausado. Elegí Simulación antes de reanalizar'; end if;

  update public.auto_moderation_signals_v77
  set active=false
  where created_at>=now()-make_interval(days=>v_days);

  for v_row in
    select source.id
    from(
      select m.id,
        coalesce(
          nullif(to_jsonb(m)->>'confirmed_at','')::timestamptz,
          nullif(to_jsonb(m)->>'created_at','')::timestamptz
        ) as occurred_at
      from public.matches m
      where lower(coalesce(to_jsonb(m)->>'result_status',''))='confirmed'
        and lower(coalesce(to_jsonb(m)->>'match_type','')) in('ranked','competitive')
        and coalesce(
          nullif(to_jsonb(m)->>'confirmed_at','')::timestamptz,
          nullif(to_jsonb(m)->>'created_at','')::timestamptz
        )>=now()-make_interval(days=>v_days)
      order by occurred_at desc
      limit v_limit
    ) source
    order by source.occurred_at asc
  loop
    perform public.tt_v77_evaluate_match(v_row.id,false);
    v_count:=v_count+1;
  end loop;

  insert into public.auto_moderation_actions_v77(action,mode,details,actor_id)
  values('simulation_reprocessed','observe',jsonb_build_object('days',v_days,'matches',v_count),v_admin);

  return public.admin_get_auto_moderation_v77(50)||jsonb_build_object('reprocessed_matches',v_count);
end;
$function$;

