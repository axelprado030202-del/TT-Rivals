  values('mode_changed',p_mode,jsonb_build_object('previous_cases_are_not_enforced',true),v_admin);

  return public.admin_get_auto_moderation_v77(50);
end;
$function$;

create or replace function public.admin_dismiss_auto_moderation_case_v77(
  p_case_id bigint,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
