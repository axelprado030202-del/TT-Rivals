create table if not exists tt_private_v77.auto_moderation_config_v77(
  singleton boolean primary key default true check(singleton),
  mode text not null default 'observe' check(mode in('observe','enforce','paused')),
  score_threshold integer not null default 100 check(score_threshold between 50 and 500),
  lookback_days integer not null default 7 check(lookback_days between 1 and 30),
  min_matches integer not null default 3 check(min_matches between 2 and 20),
  min_signal_types integer not null default 2 check(min_signal_types between 2 and 4),
  base_suspension_hours integer not null default 24 check(base_suspension_hours between 1 and 168),
  updated_by uuid,
  updated_at timestamptz not null default now()
);

